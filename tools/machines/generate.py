"""Generate link-time descriptors from the single source-bound registry."""
from tools.machines.registry import machines, ROOT


def descriptors():
    lines = ['/* Generated by tools.machines.generate; do not edit. */']
    disposal=any(m['native']['enabled'] and m['native']['entry_points']['dispose'] for m in machines())
    lines += [f'#define MD_HAS_DISPOSAL {int(disposal)}']
    for m in machines():
        n = m['native']
        if n['enabled']:
            p = n['prefix']
            lines += [f'extern void {p}_slot_init(void *);',
                      f'extern void {p}_slot_process(void *, uint32_t, uint32_t, const int32_t *, float *);']
    lines += ['const uint32_t md_param_offsets[8] = {250u,252u,244u,248u,254u,256u,262u,260u};',
              'static const MdDescriptor md_descriptors[49] = {']
    for m in machines():
        n = m['native']
        fields = f"{n['state_bytes']}u, {n['prefix']}_slot_init, {n['prefix']}_slot_process" if n['enabled'] else '0u, 0, 0'
        lines += [f"    {{ {m['md_id']}u, {fields} }}, /* {m['selector']}: {m['name']} */"]
    lines += ['};']
    if disposal:
        for m in machines():
            name=m['native']['entry_points']['dispose'] if m['native']['enabled'] else None
            if name: lines += [f'extern void {name}(void *);']
        lines += ['static const MdInit md_disposals[49] = {']
        lines += ['    '+(m['native']['entry_points']['dispose'] or '0')+',' if m['native']['enabled'] else '    0,' for m in machines()]
        lines += ['};']
    return '\n'.join(lines + [''])


if __name__ == '__main__':
    (ROOT / 'tools/machines/descriptors.h').write_text(descriptors())
